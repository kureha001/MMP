// ハンドラ関連処理
//--------------------------------------------------------
// シリアルはセットアップ処理内で事前に初期化している為、
// ここでの通信資源生成はない。
//
// start()
// ├ 空SLOT生成
// └ SLOT割当(物理ポート毎に固定で割り当て)
//--------------------------------------------------------
