//--------------------------------------------------------
//【目的】
// ・アダプタのトリガを実行する
// ・各プロセスの共通処理を提供する
//--------------------------------------------------------
//【アダプタのトリガ】
//・INIT_ADAPTER()：アダプタを初期化
//・KICK_HANDLE() ：ダプタをポーリング
//--------------------------------------------------------
