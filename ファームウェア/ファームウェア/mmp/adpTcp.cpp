//【目的】
// リクエストに従い、ＭＭＰコマンドを実行して、
// 結果をレスポンスする。
//--------------------------------------------------------
//【処理機能】
//・TCP接続毎に資源の実体をスロットに割り当てる。
//・ポーリング跨りでストリーム処理するため接続数だけスロットを消費する。
//--------------------------------------------------------
// Ver 1.2.1 (2026/08/26) 
// ・全体のロジックをシンプル化
