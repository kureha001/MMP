//━━━━━━━━━━━━━━━━━━━━━━━━━━━━
// クラス【非同期キュー型＋スロット型】
//━━━━━━━━━━━━━━━━━━━━━━━━━━━━
class  AD_UART: // 接続識別子：Stream*
public AD_API_Queue<Stream*>, // 非同期キュー型
public AD_API_Slot< Stream*>  // 接続スロット型
{
private:
//========================================================
//§最終処理
//========================================================
  //───────────────────────────
  // 終了処理：接続元に処理結果を送信する
  //───────────────────────────
  void SEND_RESULT(Stream* argConn) override final {
    //┬
    //○接続元に処理結果を送信する
    //●コンテクスト・ログを出力する
    argConn->print(ctx.base.Result);
    adpFnBase::LOG_CTX();
    //┴
  } /* SEND_RESULT() */

//========================================================
//§受信処理
//========================================================
  //───────────────────────────
  // 並列処理の内容を定義
  //───────────────────────────
  void ON_RECIVE() override final {
  //┬
  //○┐【前処理】
    //┴
  //│
  //○┐【主処理】
    //◎┐データ受信したスロットをキュー登録する
    for (int qSID = 0; qSID < SLOTs; qSID++) {
      //│＼（全スロットを走査し終えた場合）
      //│ ▼完了：走査を終える
      //│
      //○┐キュー登録に必要な情報を用意する
        //●フレーム求める
        String qFrame = adpFnStream::GET_FRAME(*(TBL[qSID].CONN));
        if (qFrame != "") continue;
        //│＼（受信データがない場合）
        //│ ▽次へ：次のスロットの走査へ進む
        //┴
      //│
      //●キューを登録する
       pushQueue(TBL[qSID].CONN, qFrame, qSID);
      //┴
    } //～for
    //┴
  //│
  //○┐【後処理】
  //┴┴
  } /* ON_RECIVE() */

//========================================================
//§ モード別実装のインクルード
//--------------------------------------------------------
//【モード別ポート利用】
// +----------+--------+--------+--------+-----------------+
// |動作モード| Serial | Serial1| Serial2| 備考            |
// +----------+--------+--------+--------+-----------------+
// | メイン   |  利用  |  利用  |  利用  | Serial1は連携用 |
// | サブ     |  利用  |(未使用)|  利用  | Serial1は連携用 |
// | ブリッジ |  利用  |  利用  |  利用  | すべて利用      |
// +----------+--------+--------+--------+-----------------+
//========================================================
#if   MODE == MODE_MAIN
  #include "UART_MainBridge.cpp"  // CONSTRACT():USB+Serial1,2
#elif MODE == MODE_SUB
  #include "UART_Sub.cpp"         // CONSTRACT():USB+Serial2
#elif MODE == MODE_BRIDGE
  #include "UART_MainBridge.cpp"  // CONSTRACT():USB+Serial1,2
  #include "UART_Bridge.cpp"      // WORKFLOW(), RUN_PROCESS()
#endif

//========================================================
//§公開機能
//========================================================
public:
  //━━━━━━━━━━━━━━━━━━━━━━━━━━━
  // コンストラクタ【非同期キュー型＋スロット型】
  //━━━━━━━━━━━━━━━━━━━━━━━━━━━
  AD_UART(  MmpContext& argCtx) : // 接続識別子：Stream*
  AD_API<      Stream*>(argCtx, AID::UART), // 基本型
  AD_API_Queue<Stream*>(argCtx, AID::UART), // 非同期キュー型
  AD_API_Slot< Stream*>(argCtx, AID::UART)  // 接続スロット型
  {
  //┬
  //○┐【前処理】
    //┴
  //│
  //○┐【主処理】
    //●モード別コンストラクタを実施する
    String retMsg = CONSTRACT();
    //│
    //●データ受信のタスクを開始する
    RUN_TASK(MY_AID);
    //┴
  //│
  //○┐【後処理】
    //●コンテクスト・ログを出力する
    Log::prtln(retMsg);
  //┴┴
  } /* constractor AD_UART() */

}; /* class AD_UART */