// WebSocket通信を受け付け、
// MMPコマンドを実行して、結果をレスポンスする。
//--------------------------------------------------------
//【処理機能】
//・WebSocketサーバを起動する
//・WebSocketイベントを受信する
//・キュー内の「全リクエスト」を順次処理する
//・リクエストを取得する
//  - コールバック時にキューへ格納
//  - ポーリング時にキューからリクエストを取得
//  - キューがない場合は何も行われない
//・リクエストを基に共通情報(コンテクスト)を纏める
//・必要に応じてユーザ認証を実施する
//・MMPコマンドを実行する
//・MMPコマンドの実行結果をレスポンする
//・処理中にエラーなどがあれば適宜レスポンスする
