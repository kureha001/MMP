namespace srvSerial {
  //━━━━━━━━━━━━━━━━━
  // 初期化処理
  //----------------------------------
  // 実行元：iniSerial.h - InitSerial()
  //━━━━━━━━━━━━━━━━━
  bool start() {

    // 1) 二重起動防止
    if(ssTBL) return true ; // 接続管理TBLが準備済みか

    // 2) サーバ資源生成
    //　➡【該当処理なし】

    // 3) 接続管理TBLを作成
    CREATE_SS_TBL()       ; // 領域確保
    ATTACH_SS_SLOT()      ; // 常時接続としてスロットを固定

    // 4) ルーティング登録
    //　➡【該当処理なし】

    // 5) サーバ開始
    //　➡【該当処理なし】

    // 6) 正常終了
    return true;
  } /* start() */

  //━━━━━━━━━━━━━━━━━
  // ハンドラ入口（ポーリング入口）
  //----------------------------------
  // 実行元：mmp.ino - loop()
  //━━━━━━━━━━━━━━━━━
  void handle(){

    // 1) 起動チェック
    //　➡【該当処理なし】

    // 2) {新規接続時｜再接続時}の接続管理スロット作成
    //　➡【該当処理なし】

    // 3) ルーティング処理
    int maxCount = PORTS_SERIAL; // シリアルポート総数
    for (int id = 0; id < maxCount; id++) routeMMP(ssTBL[id]);

  } /* handle() */

} /* namespace srvSerial */
