namespace devIIC {
//========================================================
// 基本設計
//========================================================
  //━━━━━━━━━━━━━━━━━
  // ピンアサイン
  //━━━━━━━━━━━━━━━━━
  #if   (BOARD == BOARD_ESP32_S3_TINY)
    int SDA=16, SCL=15;
  #elif (BOARD == BOARD_M5STAMP_S3   )
    int SDA=13, SCL=15;
  #elif (BOARD == BOARD_PICO2W       )
    int SDA=4 , SCL= 5;
  #else
    int SDA=0 , SCL= 0;
  #endif

//========================================================
// 担務（公開機能）
//========================================================
  //━━━━━━━━━━━━━━━━━
  // 基本情報
  //━━━━━━━━━━━━━━━━━
  bool ENABLED = false; // 有効判定：有効：true、無効：false

  //━━━━━━━━━━━━━━━━━
  // 初期化処理
  //━━━━━━━━━━━━━━━━━
  void START(){
    //┬
    //○IICを開始
    Wire.begin(SDA,SCL);
    //│
    //○有効性セット
    Serial.printf("　[OK] IIC       -> SDA[%d],SCL[%d]\n", SDA, SCL);
    //│
    //○有効性セット
    ENABLED = true;
    //┴
  } /* START() */
} /* namespace devUART */